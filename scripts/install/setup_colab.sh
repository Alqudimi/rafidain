#!/usr/bin/env bash
# Rafidain Google Colab installer + live web/tunnel launcher.
# Usage:
#   !curl -fsSL https://raw.githubusercontent.com/Alqudimi/rafidain/main/scripts/install/setup_colab.sh | bash -s -- --engine mock
set -Eeuo pipefail

[[ "${1:-}" == "-h" || "${1:-}" == "--help" ]] && {
  cat <<'USAGE'
Usage: bash setup_colab.sh [options]

Installs Rafidain with uv, starts the web UI, downloads cloudflared,
opens a temporary Cloudflare Tunnel, prints the public URLs, and streams
server/tunnel logs until the Colab cell is interrupted.

Options are forwarded to setup_uv.sh:
  --engine mock|seedvc   engine selection
  --port N               local port (default 8000)
  --no-models            skip model download
  --no-tests             skip tests
  --no-auth              disable API authentication
  --no-serve             install only; do not launch the web UI
USAGE
  exit 0
}

RAFIDAIN_GIT="https://github.com/Alqudimi/rafidain"
SELF="${BASH_SOURCE[0]:-$0}"
SELF_DIR="$(cd -- "$(dirname -- "$SELF")" 2>/dev/null && pwd -P || pwd -P)"
ROOT="$(cd -- "$SELF_DIR/../.." 2>/dev/null && pwd -P || true)"
if [[ ! -f "$ROOT/scripts/install/setup_uv.sh" ]]; then
  ROOT="${RAFIDAIN_HOME:-$PWD/rafidain}"
  if [[ ! -f "$ROOT/scripts/install/setup_uv.sh" ]]; then
    command -v git >/dev/null 2>&1 || { echo "git مطلوب لتنزيل المشروع: $RAFIDAIN_GIT" >&2; exit 1; }
    rm -rf "$ROOT"
    git clone --depth 1 "$RAFIDAIN_GIT" "$ROOT"
  fi
fi
cd "$ROOT"
export RAFIDAIN_COLAB=1
export HF_HUB_DISABLE_XET="${HF_HUB_DISABLE_XET:-1}"

ENGINE="auto"
PORT="${RAFIDAIN_PORT:-8000}"
NO_SERVE=0
FORWARD=()
while (($#)); do
  case "$1" in
    --engine) ENGINE="${2:?missing engine}"; FORWARD+=("$1" "$2"); shift 2 ;;
    --port) PORT="${2:?missing port}"; FORWARD+=("$1" "$2"); shift 2 ;;
    --no-serve) NO_SERVE=1; FORWARD+=("$1"); shift ;;
    --no-tunnel) shift ;; # Colab always opens the requested temporary tunnel.
    *) FORWARD+=("$1"); shift ;;
  esac
done

# Install/sync only once. The launcher below owns the long-lived processes.
bash "$ROOT/scripts/install/setup_uv.sh" --no-tunnel --no-serve "${FORWARD[@]}"
[[ "$NO_SERVE" == 1 ]] && exit 0

if [[ "$ENGINE" == "auto" ]]; then
  if command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi >/dev/null 2>&1; then ENGINE="seedvc"; else ENGINE="mock"; fi
fi

# The environment file generated by setup_uv.sh is authoritative.
if [[ -f .env ]]; then
  while IFS='=' read -r key value; do
    case "$key" in
      RAFIDAIN__PORT) [[ "$PORT" == "${RAFIDAIN_PORT:-8000}" ]] && PORT="${value:-$PORT}" ;;
    esac
  done < .env
fi

SERVER_TAIL_PID=""
TUNNEL_TAIL_PID=""
cleanup() {
  set +e
  [[ -n "$SERVER_TAIL_PID" ]] && kill "$SERVER_TAIL_PID" 2>/dev/null || true
  [[ -n "$TUNNEL_TAIL_PID" ]] && kill "$TUNNEL_TAIL_PID" 2>/dev/null || true
  echo "[rafidain] إيقاف الخادم والنفق..."
  uv run --python 3.11 python scripts/manage.py stop >/dev/null 2>&1 || true
}
trap cleanup INT TERM EXIT

rm -rf .run
mkdir -p .run
export RAFIDAIN__LOG_JSON=false
if [[ "$ENGINE" == "mock" ]]; then
  uv run --python 3.11 python scripts/manage.py web --mock --port "$PORT" --wait 180
else
  uv run --python 3.11 python scripts/manage.py web --port "$PORT" --wait 600
fi

# This command downloads the correct cloudflared binary into tools/ when absent,
# starts the free quick tunnel, waits for its URL, and stores it in .run/tunnel.url.
uv run --python 3.11 python scripts/manage.py tunnel start --port "$PORT"
PUBLIC_URL="$(cat .run/tunnel.url)"

echo ""
echo "============================================================"
echo " Rafidain Colab is live"
echo "============================================================"
echo "الرابط العام المؤقت: $PUBLIC_URL"
echo "لوحة التحكم:         $PUBLIC_URL/web"
echo "البث الحي:           $PUBLIC_URL/live"
echo "API:                 $PUBLIC_URL/docs"
echo "السجلات الحية:       server.log + tunnel.log"
echo "إيقاف التشغيل:       Interrupt/Stop cell"
echo "============================================================"
echo ""

# Keep the Colab cell alive and stream both logs with an unambiguous prefix.
tail -n 30 -F .run/server.log 2>/dev/null | sed -u 's/^/[server] /' &
SERVER_TAIL_PID=$!
tail -n 30 -F .run/tunnel.log 2>/dev/null | sed -u 's/^/[cloudflared] /' &
TUNNEL_TAIL_PID=$!
wait "$SERVER_TAIL_PID" "$TUNNEL_TAIL_PID"
